def std(case, s):
    """Inputs shared by most exercises: arrays sized from n (and m)."""
    n, m = s.get("n", 0), s.get("m", s.get("n", 0))
    s.update(A=list(range(1, n + 1)), B=[0] * max(n, 1), C=[0] * max(n, 1), P=[0] * max(n, 1), R=[0] * max(n, 1),
             M=[[i + j for j in range(max(m, 1))] for i in range(max(n, 1))],
             X=[[1] * max(n, 1) for _ in range(max(n, 1))], Y=[[2] * max(n, 1) for _ in range(max(n, 1))],
             Z=[[0] * max(n, 1) for _ in range(max(n, 1))], v=list(range(max(m, 1))), y=[0] * max(n, 1),
             a=3, b=4, c=5, x=7, x1=1, y1=2, x2=4, y2=6, low=0, high=max(n - 1, 0), count=0, total=0, target=-1)
    return s


def ex(id, level, topic, title, name, params, body, sizes=SMALL, setup=std, **kw):
    d = dict(id=id, level=level, topic=topic, title=title, name=name, params=params, body=body, sizes=sizes, setup=setup)
    d.update(kw)
    return d


